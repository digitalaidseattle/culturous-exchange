/**
 *  terrainGrid.ts
 *
 *  A rough map of what the land of the world is like, for coloring the globes: one digit
 *  for each 3 degree square of the earth, 120 squares across (west to east from 180 degrees west)
 *  and 60 down (north to south from the north pole). It is meant to show the broad character of the
 *  land, such as the Sahara, the Amazon, the Siberian forest, the Himalaya and the ice caps, and
 *  not to be exact at the scale of a country.
 *
 *  Made once, by sorting the land of a day time picture of the earth (the Earth picture in the
 *  three-globe examples, which is made from NASA and Natural Earth imagery) into the classes below by
 *  its color, treating high ground as rock, and filling the sea squares next to the coast with the
 *  nearest land so that colors fade into each other along it. Nothing else is read from the picture.
 *
 *  @copyright 2026 Digital Aid Seattle
 *
 */

